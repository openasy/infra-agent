// What an admin puts on a host so this agent can read it (ADR 0031): an account, one sshd drop-in and, if they want
// the details that need root, a sudoers file. Nothing else is installed.

/** The commands collect.sh runs through `p`, with exactly the same arguments. */
export const PRIVILEGED: Array<{ cmd: string; args: string; reads: string }> = [
  { cmd: "cat", args: "/sys/class/dmi/id/product_serial", reads: "the hardware serial number" },
  { cmd: "cat", args: "/sys/class/dmi/id/product_uuid", reads: "the hardware UUID, which the server's BMC reports too" },
  { cmd: "ss", args: "-H -tulnp", reads: "which process listens on each port" },
  { cmd: "netstat", args: "-tulnp", reads: "which process listens on each port, without ss" },
  { cmd: "ls", args: "-1 /var/spool/cron/crontabs", reads: "which users have a crontab" },
  { cmd: "passwd", args: "-S -a", reads: "whether each account has a password or is locked, never the hash" },
  { cmd: "cat", args: "/etc/sudoers", reads: "who may use sudo" },
  { cmd: "find", args: "/etc/sudoers.d -maxdepth 1 -type f -print -exec cat {} ;", reads: "who may use sudo, from sudoers.d" },
  {
    cmd: "find",
    args: "/root /home -maxdepth 3 -name authorized_keys -type f -print -exec ssh-keygen -lf {} ;",
    reads: "the fingerprints of SSH keys that may log in",
  },
  { cmd: "sshd", args: "-T", reads: "the SSH server's effective settings" },
  { cmd: "nft", args: "list ruleset", reads: "the firewall rules" },
  { cmd: "iptables-save", args: "", reads: "the firewall rules, without nftables" },
];

/** Where distributions install these commands; sudo matches the full path, so every likely one is listed. */
const DIRS = ["/usr/bin", "/usr/sbin", "/bin", "/sbin"];

export const ACCOUNT = "openasy";

export function sudoers(account = ACCOUNT): string {
  // A command listed without arguments would allow any arguments; "" allows none (sudoers(5)).
  const entries = PRIVILEGED.flatMap(({ cmd, args }) => DIRS.map((d) => `${d}/${cmd} ${args || '""'}`));
  return [
    "# OpenAsy infra-agent: read-only commands with fixed arguments and no wildcards (ADR 0031).",
    "# Generated by infra-agent to match its script; install it as /etc/sudoers.d/openasy with mode 0440 and check it with visudo -c.",
    `Cmnd_Alias OPENASY_READ = ${entries.join(", \\\n    ")}`,
    `Defaults:${account} !requiretty, !lecture, !mail_badpass`,
    `${account} ALL=(root) NOPASSWD: OPENASY_READ`,
    "",
  ].join("\n");
}

export function sshdConfig(account = ACCOUNT): string {
  return [
    "# /etc/ssh/sshd_config.d/openasy.conf",
    "# Trust the infra-agent certificate authority only for the principals listed per account, so it can never log",
    "# in as root or anyone else.",
    "TrustedUserCAKeys /etc/ssh/openasy_ca.pub",
    "AuthorizedPrincipalsFile /etc/ssh/principals/%u",
    `Match User ${account}`,
    "  PasswordAuthentication no",
    "  AllowTcpForwarding no",
    "  AllowAgentForwarding no",
    "  AllowStreamLocalForwarding no",
    "  X11Forwarding no",
    "  PermitTTY no",
    "",
  ].join("\n");
}

/** Shell commands for an admin to run once on a host, as root. */
export function hostSetup(caPublicKey: string, opts: { sudo: boolean; containers: boolean; account?: string }): string {
  const a = opts.account ?? ACCOUNT;
  const lines = [
    `# Run as root on the host. Creates the ${a} account, trusts the infra-agent CA for it only, and reloads sshd.`,
    `useradd --create-home --shell /bin/sh ${a} && passwd -l ${a}`,
    `install -d -m 755 /etc/ssh/principals && echo ${a} > /etc/ssh/principals/${a}`,
    `echo '${caPublicKey}' > /etc/ssh/openasy_ca.pub`,
    `cat > /etc/ssh/sshd_config.d/openasy.conf <<'OPENASY'`,
    ...sshdConfig(a).trimEnd().split("\n").slice(1),
    "OPENASY",
    "sshd -t && (systemctl reload ssh 2>/dev/null || systemctl reload sshd)",
  ];
  if (opts.sudo) {
    lines.push(
      "",
      "# Optional: the read-only commands that need root.",
      "cat > /etc/sudoers.d/openasy <<'OPENASY'",
      ...sudoers(a).trimEnd().split("\n"),
      "OPENASY",
      "chmod 440 /etc/sudoers.d/openasy && visudo -cf /etc/sudoers.d/openasy",
    );
  }
  if (opts.containers) {
    lines.push("", "# Optional: containers. Access to the Docker socket is equivalent to root on this host (ADR 0031).", `usermod -aG docker ${a}`);
  }
  return lines.join("\n") + "\n";
}

/** For hosts that cannot change sshd_config: one fixed key, without forwarding, TTY or agent. */
export const authorizedKeyLine = (publicKey: string) => `restrict ${publicKey.trim()}`;
